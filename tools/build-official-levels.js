'use strict';

const fs = require('node:fs');
const path = require('node:path');

function readJSON(filename) {
  try {
    return JSON.parse(fs.readFileSync(filename, 'utf8'));
  } catch (error) {
    throw new Error(`${filename}: ${error.message}`, { cause: error });
  }
}

function buildOfficialLevels(root = path.resolve(__dirname, '..')) {
  const directory = path.join(root, 'levels', 'official');
  const manifestPath = path.join(directory, 'campaign.json');
  const manifest = readJSON(manifestPath);
  const fail = message => { throw new Error(`${manifestPath}: ${message}`); };
  if (!manifest || manifest.version !== 1 || !Array.isArray(manifest.levels)) {
    fail('Expected version 1 and a levels array.');
  }
  // Validation uses the engine's existing schema; the checked-in bundle also permits direct file:// play.
  const { validateCustomLevel } = require('../src/game.js');
  const { OFFICIAL_WORLDS } = require('../src/campaign.js');
  const worlds = new Map(OFFICIAL_WORLDS.map(world => [world.id, world]));
  const ids = new Map(), numbers = new Map(), names = new Map(), files = new Map();
  const publishedWorlds = new Set(manifest.levels.map(entry => entry?.worldId));
  for (const world of OFFICIAL_WORLDS.filter(world => !world.mapOnly && !publishedWorlds.has(world.id))) {
    ids.set(`official-${world.id}-1`, `temporary starter in world ${world.id}`);
    names.set(`${world.name} Starter`, `temporary starter in world ${world.id}`);
  }
  const unique = (map, key, label, source) => {
    if (map.has(key)) fail(`${source}: duplicate ${label} "${key}" (also used by ${map.get(key)}).`);
    map.set(key, source);
  };
  const text = (value, label, source) => {
    if (typeof value !== 'string' || !value.trim() || value !== value.trim() || value.length > 60) {
      fail(`${source}: ${label} must be a nonempty, trimmed string of at most 60 characters.`);
    }
    return value;
  };
  const levels = manifest.levels.map((entry, index) => {
    const source = entry?.file ?? `entry ${index + 1}`;
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) fail(`${source}: expected a level entry.`);
    const worldId = text(entry.worldId, 'worldId', source);
    const world = worlds.get(worldId);
    if (!world || world.mapOnly) fail(`${source}: unknown or nonplayable world "${worldId}".`);
    const number = text(entry.number, 'number', source);
    const id = text(entry.id, 'permanent id', source);
    if (typeof entry.file !== 'string' || !entry.file.endsWith('.json') || entry.file.includes('\\')
      || path.posix.isAbsolute(entry.file) || entry.file.split('/').some(part => !part || part === '.' || part === '..')
      || entry.file.includes(':') || entry.file === 'campaign.json') {
      fail(`${source}: file must be a relative JSON path inside levels/official, using "/" separators.`);
    }
    const filename = path.resolve(directory, ...entry.file.split('/'));
    let realFile;
    try {
      realFile = fs.realpathSync(filename);
      const relative = path.relative(fs.realpathSync(directory), realFile);
      if (relative.startsWith('..') || path.isAbsolute(relative)) fail(`${source}: file is outside levels/official.`);
    } catch (error) {
      throw new Error(`${filename}: ${error.message}`, { cause: error });
    }
    unique(files, realFile, 'source file', source);
    unique(ids, id, 'permanent id', source);
    unique(numbers, `${worldId}:${number}`, 'world/level number', source);
    let level;
    try {
      level = validateCustomLevel(readJSON(filename));
    } catch (error) {
      throw new Error(`${filename}: ${error.message}`, { cause: error });
    }
    unique(names, level.id, 'level name', source);
    return { worldId, number, id, level };
  });
  const output = '// Generated by tools/build-official-levels.js. Do not edit.\n'
    + "(function () {\n'use strict';\n"
    + `const levels = ${JSON.stringify(levels, null, 2)};\n`
    + "if (typeof module !== 'undefined' && module.exports) module.exports = levels;\n"
    + 'else globalThis.KoshiOfficialLevels = levels;\n})();\n';
  const outputPath = path.join(root, 'src', 'official-levels.generated.js');
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output) {
    const temporary = `${outputPath}.${process.pid}.tmp`;
    try {
      fs.writeFileSync(temporary, output);
      fs.renameSync(temporary, outputPath);
    } finally {
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    }
  }
  return levels;
}

if (require.main === module) {
  try {
    const levels = buildOfficialLevels();
    console.log(`Generated ${levels.length} authored Official level(s).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { buildOfficialLevels };
